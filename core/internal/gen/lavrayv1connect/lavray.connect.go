	CreateProfile(context.Context, *connect.Request[lavrayv1.CreateProfileRequest]) (*connect.Response[lavrayv1.Profile], error)
	UpdateProfile(context.Context, *connect.Request[lavrayv1.UpdateProfileRequest]) (*connect.Response[lavrayv1.UpdateProfileResponse], error)
	// Запрещено для запущенного профиля (FR-UI-038) → FAILED_PRECONDITION.
	DeleteProfile(context.Context, *connect.Request[lavrayv1.DeleteProfileRequest]) (*connect.Response[lavrayv1.Empty], error)
	// Массовые операции таблицы: FR-UI-035 (Move), FR-UI-036 (Clone),
	// FR-UI-037/212 (Reset Traffic), FR-UI-074 (Reorder/Drag&Drop),
	// FR-UI-042 (Remove Unavailable / Remove Duplicates).
	MoveProfiles(context.Context, *connect.Request[lavrayv1.MoveProfilesRequest]) (*connect.Response[lavrayv1.Empty], error)
	CloneProfiles(context.Context, *connect.Request[lavrayv1.CloneProfilesRequest]) (*connect.Response[lavrayv1.CloneProfilesResponse], error)
