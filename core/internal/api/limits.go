package api

// MaxRequestBytes — предел размера ОДНОГО сообщения запроса RPC (T-50, A1-14).
// Раньше тело не ограничивалось: любой локальный процесс с токеном мог
// отправить сотни МиБ в ImportContent и раздуть память ядра. Лимит действует
// и на распакованное gzip-тело. Самое большое законное сообщение — содержимое
// подписки/файла в ImportContent; 16 МиБ — это ≈ 80 тыс. ссылок при лимите
// парсера в 10 000 профилей.
const MaxRequestBytes = 16 << 20
