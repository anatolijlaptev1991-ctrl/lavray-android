package traffic

// Source — источник данных о соединениях запущенного инстанса. Реализации
// горутинно-безопасны. Источник живёт ровно столько же, сколько инстанс:
// после остановки инстанса менеджер перестаёт его отдавать.
type Source interface {
	// Active — активные соединения (порядок не определён).
	Active() []ConnInfo
	// Closed — недавно закрытые соединения (источник хранит ограниченное число).
	Closed() []ConnInfo
	// Total — байты за всё время жизни источника: активные, закрытые и уже
	// вытесненные из списка закрытых. Значения не убывают.
	Total() (up, down int64)
	// Close закрывает активное соединение; ErrNotFound — такого нет.
	Close(id string) error
	// Subscribe подписывает на открытия и закрытия соединений. Канал не
	// блокирует источник: при переполнении события теряются, поэтому события —
	// подсказка, а список истины — Active. cancel отписывает и закрывает канал.
	Subscribe() (<-chan Event, func())
}
