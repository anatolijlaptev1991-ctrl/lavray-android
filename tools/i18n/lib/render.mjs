import { sortedCategories } from './classify.mjs';
import { toAndroidText } from './escape.mjs';
import { GENERATOR_PATH } from './languages.mjs';
import { numberingFor } from './placeholders.mjs';

const INDENT = '    ';

export const FILE_HEADER = [
  '<?xml version="1.0" encoding="utf-8"?>',
  '<!-- SPDX-License-Identifier: GPL-3.0-only -->',
  `<!-- GENERATED by ${GENERATOR_PATH} from the desktop dictionaries and tools/i18n/android/*.json. DO NOT EDIT. -->`,
].join('\n');

function textOptions(entry) {
  const numbering = numberingFor(entry.placeholders);
  return { numbering, formatMode: numbering.size > 0 };
}

function renderString(entry, lang) {
  const options = textOptions(entry);
  const raw = entry.values[lang];
  const formatted = !options.formatMode && raw.includes('%') ? ' formatted="false"' : '';
  return `${INDENT}<string name="${entry.name}"${formatted}>${toAndroidText(raw, options)}</string>`;
}

function renderPlurals(entry, lang) {
  const options = textOptions(entry);
  const items = entry.items[lang];
  const lines = sortedCategories(new Map(Object.entries(items))).map(
    (category) => `${INDENT}${INDENT}<item quantity="${category}">${toAndroidText(items[category], options)}</item>`,
  );
  return [`${INDENT}<plurals name="${entry.name}">`, ...lines, `${INDENT}</plurals>`].join('\n');
}

export function renderEntry(entry, lang) {
  return entry.kind === 'plurals' ? renderPlurals(entry, lang) : renderString(entry, lang);
}

/** Renders the complete strings.xml of one language (entries are expected sorted by name). */
export function renderResources(lang, entries) {
  const body = entries.map((entry) => renderEntry(entry, lang));
  return `${[FILE_HEADER, '<resources>', ...body, '</resources>'].join('\n')}\n`;
}
